CREATE OR REPLACE PACKAGE inventory_pkg AS
    c_default_multiplier CONSTANT PLS_INTEGER := 2;

    FUNCTION availability (p_product_id IN NUMBER) RETURN stock_tab PIPELINED;
    -- What restock would order, without ordering it.
    FUNCTION restock_plan (p_warehouse_id IN NUMBER DEFAULT NULL) RETURN stock_tab PIPELINED;
    PROCEDURE restock (p_warehouse_id IN NUMBER DEFAULT NULL);
END inventory_pkg;
/

CREATE OR REPLACE PACKAGE BODY inventory_pkg AS
    FUNCTION multiplier RETURN PLS_INTEGER IS
        v_value NUMBER;
    BEGIN
        SELECT TO_NUMBER(setting_value DEFAULT NULL ON CONVERSION ERROR) INTO v_value
        FROM app_settings WHERE setting_key = 'inventory.restock_multiplier';
        RETURN NVL(v_value, c_default_multiplier);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN c_default_multiplier;
    END multiplier;

    FUNCTION availability (p_product_id IN NUMBER) RETURN stock_tab PIPELINED IS
    BEGIN
        FOR r IN (SELECT w.code, s.product_id, p.sku, s.available, s.reorder_level
                  FROM stock s
                  JOIN warehouses w ON w.warehouse_id = s.warehouse_id
                  JOIN products p ON p.product_id = s.product_id
                  WHERE s.product_id = p_product_id
                  ORDER BY w.code) LOOP
            PIPE ROW (stock_row_t(r.code, r.product_id, r.sku, r.available, r.reorder_level, NULL));
        END LOOP;
        RETURN;
    END availability;

    FUNCTION restock_plan (p_warehouse_id IN NUMBER DEFAULT NULL) RETURN stock_tab PIPELINED IS
        v_multiplier PLS_INTEGER := multiplier;
    BEGIN
        FOR r IN (SELECT w.code, s.product_id, p.sku, s.available, s.reorder_level
                  FROM stock s
                  JOIN warehouses w ON w.warehouse_id = s.warehouse_id
                  JOIN products p ON p.product_id = s.product_id
                  WHERE s.available <= s.reorder_level AND p.discontinued = 0
                    AND (p_warehouse_id IS NULL OR s.warehouse_id = p_warehouse_id)
                  ORDER BY w.code, p.sku) LOOP
            PIPE ROW (stock_row_t(r.code, r.product_id, r.sku, r.available, r.reorder_level,
                                  r.reorder_level * v_multiplier - r.available));
        END LOOP;
        RETURN;
    END restock_plan;

    PROCEDURE restock (p_warehouse_id IN NUMBER DEFAULT NULL) IS
    BEGIN
        INSERT INTO stock_movements (warehouse_id, product_id, qty, reason)
        SELECT w.warehouse_id, t.product_id, t.order_qty, 'receipt'
        FROM TABLE(inventory_pkg.restock_plan(p_warehouse_id)) t
        JOIN warehouses w ON w.code = t.warehouse;
        COMMIT;
    END restock;
END inventory_pkg;
