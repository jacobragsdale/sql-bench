CREATE OR REPLACE TRIGGER trg_stock_movements_apply
AFTER INSERT ON stock_movements
FOR EACH ROW
BEGIN
    UPDATE stock SET on_hand = on_hand + :NEW.qty, updated_at = SYSTIMESTAMP
    WHERE warehouse_id = :NEW.warehouse_id AND product_id = :NEW.product_id;
END;
/

