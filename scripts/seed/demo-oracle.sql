CREATE OR REPLACE PACKAGE BODY report_pkg AS
    FUNCTION sales_report (
        p_from     IN DATE DEFAULT ADD_MONTHS(TRUNC(SYSDATE), -12),
        p_to       IN DATE DEFAULT TRUNC(SYSDATE),
        p_group_by IN VARCHAR2 DEFAULT 'month'
    ) RETURN sales_tab PIPELINED IS
        v_bucket VARCHAR2(200);
        v_cur    SYS_REFCURSOR;
        v_row    sales_row_t := sales_row_t(NULL, NULL, NULL, NULL, NULL, NULL);
    BEGIN
        v_bucket := CASE LOWER(p_group_by)
            WHEN 'day' THEN 'TO_CHAR(o.ordered_at, ''YYYY-MM-DD'')'
            WHEN 'week' THEN 'TO_CHAR(TRUNC(o.ordered_at, ''IW''), ''YYYY-MM-DD'')'
            WHEN 'month' THEN 'TO_CHAR(o.ordered_at, ''YYYY-MM'')'
            WHEN 'category' THEN 'cat.name'
            WHEN 'warehouse' THEN 'w.code'
            WHEN 'rep' THEN 'NVL(TO_CHAR(e.full_name), ''(house)'')'
        END;
        IF v_bucket IS NULL THEN
            RAISE_APPLICATION_ERROR(-20020, 'group_by is day, week, month, category, warehouse or rep.');
        END IF;

        OPEN v_cur FOR
            'SELECT ' || v_bucket || ', COUNT(DISTINCT o.order_id), SUM(ol.qty),
                    SUM(ol.line_total), SUM(ol.qty * p.unit_cost)
             FROM orders o
             JOIN order_lines ol ON ol.order_id = o.order_id
             JOIN products p ON p.product_id = ol.product_id
             JOIN categories cat ON cat.category_id = p.category_id
             JOIN warehouses w ON w.warehouse_id = o.warehouse_id
             LEFT JOIN employees e ON e.employee_id = o.sales_rep_id
             WHERE o.ordered_at >= :f AND o.ordered_at < :t + 1
               AND o.status NOT IN (''cancelled'', ''refunded'')
             GROUP BY ' || v_bucket || '
             ORDER BY ' || CASE WHEN LOWER(p_group_by) IN ('day', 'week', 'month') THEN '1' ELSE '4 DESC' END
            USING p_from, p_to;
        LOOP
            FETCH v_cur INTO v_row.bucket, v_row.orders, v_row.units, v_row.revenue, v_row.cost;
            EXIT WHEN v_cur%NOTFOUND;
            v_row.gross_margin := v_row.revenue - v_row.cost;
            PIPE ROW (v_row);
        END LOOP;
        CLOSE v_cur;
        RETURN;
    END sales_report;

    PROCEDURE refresh_daily_sales IS
    BEGIN
        DBMS_MVIEW.REFRESH('MV_DAILY_SALES', 'C');
    END refresh_daily_sales;
END report_pkg;
