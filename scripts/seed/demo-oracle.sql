CREATE OR REPLACE VIEW v_order_summary AS
SELECT o.order_id, o.order_no, o.ordered_at, o.status,
       c.customer_id, c.first_name || ' ' || c.last_name AS customer_name, c.tier,
       e.full_name AS sales_rep, w.code AS warehouse,
       l.line_count, l.units, o.subtotal, o.discount, o.tax, o.total
FROM orders o
JOIN customers c ON c.customer_id = o.customer_id
JOIN warehouses w ON w.warehouse_id = o.warehouse_id
LEFT JOIN employees e ON e.employee_id = o.sales_rep_id
OUTER APPLY (SELECT COUNT(*) AS line_count, SUM(ol.qty) AS units
             FROM order_lines ol WHERE ol.order_id = o.order_id) l;

CREATE OR REPLACE VIEW v_customer_360 AS
WITH stats AS (
    SELECT customer_id, COUNT(*) AS orders, SUM(total) AS lifetime_value,
           MIN(ordered_at) AS first_order_at, MAX(ordered_at) AS last_order_at
    FROM orders
    WHERE status NOT IN ('cancelled', 'refunded')
    GROUP BY customer_id
)
SELECT c.customer_id, c.first_name || ' ' || c.last_name AS name, c.email, c.tier,
       NVL(s.orders, 0) AS orders, NVL(s.lifetime_value, 0) AS lifetime_value,
       s.first_order_at, s.last_order_at,
       TRUNC(SYSDATE) - TRUNC(s.last_order_at) AS days_since_last_order,
       fav.category AS favorite_category, a.city, a.country
FROM customers c
LEFT JOIN stats s ON s.customer_id = c.customer_id
LEFT JOIN addresses a ON a.customer_id = c.customer_id AND a.kind = 'shipping' AND a.is_default = 1
OUTER APPLY (
    SELECT cat.name AS category
    FROM orders o
    JOIN order_lines ol ON ol.order_id = o.order_id
    JOIN products p ON p.product_id = ol.product_id
    JOIN categories cat ON cat.category_id = p.category_id
    WHERE o.customer_id = c.customer_id
    GROUP BY cat.name
    ORDER BY SUM(ol.line_total) DESC, cat.name
    FETCH FIRST 1 ROW ONLY
) fav;

CREATE OR REPLACE VIEW v_category_tree AS
SELECT category_id, parent_id, name, LEVEL - 1 AS depth,
       SUBSTR(SYS_CONNECT_BY_PATH(name, ' > '), 4) AS path,
       CONNECT_BY_ISLEAF AS is_leaf
FROM categories
START WITH parent_id IS NULL
CONNECT BY PRIOR category_id = parent_id;

CREATE OR REPLACE VIEW v_org_chart AS
WITH tree (employee_id, manager_id, full_name, title, department_id, depth, chain) AS (
    SELECT employee_id, manager_id, full_name, title, department_id, 0, CAST(full_name AS NVARCHAR2(1000))
    FROM employees WHERE manager_id IS NULL
    UNION ALL
    SELECT e.employee_id, e.manager_id, e.full_name, e.title, e.department_id, t.depth + 1,
           CAST(t.chain || ' > ' || e.full_name AS NVARCHAR2(1000))
    FROM employees e JOIN tree t ON e.manager_id = t.employee_id
    WHERE e.terminated_on IS NULL
) SEARCH DEPTH FIRST BY full_name SET sort_key
SELECT t.employee_id, LPAD(' ', 4 * t.depth) || t.full_name AS employee, t.title,
       d.name AS department, t.depth, t.chain, t.sort_key
FROM tree t JOIN departments d ON d.department_id = t.department_id;

CREATE OR REPLACE VIEW v_low_stock AS
SELECT w.code AS warehouse, p.product_id, p.sku, p.name AS product,
