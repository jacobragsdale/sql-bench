CREATE MATERIALIZED VIEW mv_daily_sales
BUILD IMMEDIATE REFRESH COMPLETE ON DEMAND AS
SELECT TRUNC(o.ordered_at) AS sales_date, o.warehouse_id,
       SUM(ol.line_total) AS revenue, SUM(ol.qty) AS units, COUNT(*) AS line_count
FROM orders o
JOIN order_lines ol ON ol.order_id = o.order_id
GROUP BY TRUNC(o.ordered_at), o.warehouse_id;

