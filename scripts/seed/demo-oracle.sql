CREATE OR REPLACE FUNCTION customer_tier (p_lifetime_value IN NUMBER) RETURN VARCHAR2 DETERMINISTIC IS
BEGIN
    RETURN CASE WHEN p_lifetime_value >= 60000 THEN 'platinum'
                WHEN p_lifetime_value >= 25000 THEN 'gold'
                WHEN p_lifetime_value >= 10000 THEN 'silver'
                ELSE 'bronze' END;
END customer_tier;
/

-- Rates exist for weekdays only, so a weekend falls back to Friday.
CREATE OR REPLACE FUNCTION fx_rate (p_currency IN VARCHAR2, p_on IN DATE DEFAULT SYSDATE) RETURN NUMBER IS
    v_rate exchange_rates.usd_per_unit%TYPE;
BEGIN
    IF p_currency = 'USD' THEN
        RETURN 1;
    END IF;
    SELECT MAX(usd_per_unit) KEEP (DENSE_RANK LAST ORDER BY rate_date) INTO v_rate
    FROM exchange_rates
    WHERE currency = p_currency AND rate_date <= TRUNC(p_on);
    IF v_rate IS NULL THEN
        RAISE_APPLICATION_ERROR(-20050, 'No ' || p_currency || ' rate on or before '
                                        || TO_CHAR(p_on, 'YYYY-MM-DD'));
    END IF;
    RETURN v_rate;
END fx_rate;
/

CREATE OR REPLACE FUNCTION to_usd (p_amount IN NUMBER, p_currency IN VARCHAR2, p_on IN DATE DEFAULT SYSDATE)
RETURN NUMBER IS
BEGIN
    RETURN ROUND(p_amount * fx_rate(p_currency, p_on), 2);
END to_usd;
/

CREATE OR REPLACE FUNCTION business_days_between (p_from IN DATE, p_to IN DATE) RETURN NUMBER DETERMINISTIC IS
    v_days NUMBER := 0;
    v_day  DATE := TRUNC(p_from);
BEGIN
    WHILE v_day < TRUNC(p_to) LOOP
        -- An 'IW' week starts on Monday whatever NLS_TERRITORY says: 0-4 are weekdays.
        IF v_day - TRUNC(v_day, 'IW') < 5 THEN
            v_days := v_days + 1;
        END IF;
        v_day := v_day + 1;
    END LOOP;
    RETURN v_days;
END business_days_between;
/

-- For trying cancel on a fetch: select * from slow_rows(30) pipes one row a second.
CREATE OR REPLACE FUNCTION slow_rows (p_rows IN NUMBER DEFAULT 30, p_seconds_each IN NUMBER DEFAULT 1)
RETURN sys.odcinumberlist PIPELINED IS
BEGIN
    FOR i IN 1 .. p_rows LOOP
        DBMS_SESSION.SLEEP(p_seconds_each);
        PIPE ROW (i);
    END LOOP;
    RETURN;
END slow_rows;
/

