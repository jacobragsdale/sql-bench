CREATE OR REPLACE PACKAGE BODY hr_pkg AS
    PROCEDURE give_raise (p_employee_id IN NUMBER, p_pct IN NUMBER, p_reason IN VARCHAR2 DEFAULT 'merit') IS
    BEGIN
        IF p_pct <= 0 OR p_pct > 25 THEN
            RAISE_APPLICATION_ERROR(-20030, 'A raise is more than 0 and at most 25 percent.');
        END IF;
        IF p_reason NOT IN ('merit', 'promotion', 'market', 'correction') THEN
            RAISE_APPLICATION_ERROR(-20031, 'reason is merit, promotion, market or correction.');
        END IF;
        g_raise_reason := p_reason;
        UPDATE employees SET salary = ROUND(salary * (1 + p_pct / 100), 2)
        WHERE employee_id = p_employee_id AND terminated_on IS NULL;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20032, 'No such active employee: ' || p_employee_id);
        END IF;
        g_raise_reason := NULL;
        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            g_raise_reason := NULL;
            RAISE;
    END give_raise;

    FUNCTION reports_to (p_manager_id IN NUMBER) RETURN org_tab PIPELINED IS
    BEGIN
        FOR r IN (SELECT employee_id, full_name, title, manager_id, LEVEL - 1 AS depth
                  FROM employees
                  START WITH employee_id = p_manager_id
                  CONNECT BY PRIOR employee_id = manager_id AND terminated_on IS NULL
                  ORDER SIBLINGS BY last_name) LOOP
            PIPE ROW (org_row_t(r.employee_id, r.full_name, r.title, r.manager_id, r.depth));
        END LOOP;
        RETURN;
    END reports_to;

    FUNCTION headcount (p_department_id IN NUMBER) RETURN NUMBER IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
        FROM employees
        WHERE terminated_on IS NULL
          AND department_id IN (SELECT department_id FROM departments
                                START WITH department_id = p_department_id
                                CONNECT BY PRIOR department_id = parent_department_id);
        RETURN v_count;
    END headcount;
END hr_pkg;
