CREATE OR REPLACE VIEW v_monthly_revenue AS
WITH m AS (
    SELECT TRUNC(ordered_at, 'MM') AS month_start, COUNT(*) AS orders, SUM(total) AS revenue
    FROM orders
    WHERE status NOT IN ('cancelled', 'refunded')
    GROUP BY TRUNC(ordered_at, 'MM')
)
SELECT month_start, orders, revenue,
       ROUND(revenue / orders, 2) AS avg_order_value,
       SUM(revenue) OVER (PARTITION BY EXTRACT(YEAR FROM month_start) ORDER BY month_start
                          ROWS UNBOUNDED PRECEDING) AS ytd_revenue,
       ROUND(100 * (revenue - LAG(revenue) OVER (ORDER BY month_start))
             / NULLIF(LAG(revenue) OVER (ORDER BY month_start), 0), 2) AS mom_growth_pct
FROM m;

CREATE OR REPLACE VIEW v_product_rankings AS
SELECT cat.name AS category, p.sku, p.name AS product,
       SUM(ol.qty) AS units, SUM(ol.line_total) AS revenue,
       RANK() OVER (PARTITION BY cat.name ORDER BY SUM(ol.line_total) DESC) AS rank_in_category,
       ROUND(100 * RATIO_TO_REPORT(SUM(ol.line_total)) OVER (PARTITION BY cat.name), 2) AS pct_of_category
FROM order_lines ol
JOIN orders o ON o.order_id = ol.order_id
JOIN products p ON p.product_id = ol.product_id
JOIN categories cat ON cat.category_id = p.category_id
WHERE o.status NOT IN ('cancelled', 'refunded')
GROUP BY cat.name, p.sku, p.name;

CREATE OR REPLACE VIEW v_ar_aging AS
SELECT i.invoice_id, o.order_no, c.first_name || ' ' || c.last_name AS customer,
       i.issued_on, i.due_on, i.amount, i.paid_amount, i.amount - i.paid_amount AS outstanding,
       TRUNC(SYSDATE) - i.due_on AS days_overdue,
       CASE WHEN TRUNC(SYSDATE) - i.due_on <= 0 THEN 'current'
            WHEN TRUNC(SYSDATE) - i.due_on <= 30 THEN '1-30'
            WHEN TRUNC(SYSDATE) - i.due_on <= 60 THEN '31-60'
            WHEN TRUNC(SYSDATE) - i.due_on <= 90 THEN '61-90'
            ELSE '90+' END AS bucket
FROM invoices i
JOIN orders o ON o.order_id = i.order_id
JOIN customers c ON c.customer_id = o.customer_id
WHERE i.paid_amount < i.amount;

