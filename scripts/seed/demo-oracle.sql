CREATE OR REPLACE PROCEDURE purge_change_log (p_older_than_days IN NUMBER DEFAULT 90,
                                              p_batch_size IN NUMBER DEFAULT 500) IS
    v_cutoff TIMESTAMP := SYSTIMESTAMP - NUMTODSINTERVAL(p_older_than_days, 'DAY');
BEGIN
    LOOP
        DELETE FROM change_log WHERE changed_at < v_cutoff AND ROWNUM <= p_batch_size;
        EXIT WHEN SQL%ROWCOUNT = 0;
        COMMIT;
    END LOOP;
    COMMIT;
END purge_change_log;
