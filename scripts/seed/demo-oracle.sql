CREATE OR REPLACE PROCEDURE refresh_customer_tiers IS
BEGIN
    MERGE INTO customers c
    USING (SELECT c2.customer_id, customer_tier(NVL(v.lifetime_value, 0)) AS tier
           FROM customers c2
           LEFT JOIN (SELECT customer_id, SUM(total) AS lifetime_value
                      FROM orders WHERE status NOT IN ('cancelled', 'refunded')
                      GROUP BY customer_id) v ON v.customer_id = c2.customer_id) t
    ON (c.customer_id = t.customer_id)
    WHEN MATCHED THEN UPDATE SET c.tier = t.tier WHERE c.tier <> t.tier;
    COMMIT;
END refresh_customer_tiers;
