CREATE OR REPLACE PACKAGE BODY sales_pkg AS

    PROCEDURE release_reservation (p_order_id IN NUMBER, p_warehouse_id IN NUMBER) IS
    BEGIN
        MERGE INTO stock s
        USING (SELECT product_id, SUM(qty) AS qty FROM order_lines
               WHERE order_id = p_order_id GROUP BY product_id) l
        ON (s.product_id = l.product_id AND s.warehouse_id = p_warehouse_id)
        WHEN MATCHED THEN UPDATE SET s.reserved = s.reserved - l.qty, s.updated_at = SYSTIMESTAMP;
    END release_reservation;

    FUNCTION promo_pct (p_promo_code IN VARCHAR2, p_on IN DATE) RETURN NUMBER IS
        v_pct promotions.pct_off%TYPE;
    BEGIN
        IF p_promo_code IS NULL THEN
            RETURN 0;
        END IF;
        SELECT pct_off INTO v_pct FROM promotions
        WHERE promo_code = p_promo_code AND TRUNC(p_on) BETWEEN starts_on AND ends_on;
        RETURN v_pct;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN 0;
    END promo_pct;

    FUNCTION tax_rate (p_warehouse_id IN NUMBER) RETURN NUMBER RESULT_CACHE IS
        v_country warehouses.country%TYPE;
    BEGIN
        SELECT country INTO v_country FROM warehouses WHERE warehouse_id = p_warehouse_id;
        RETURN CASE v_country WHEN 'US' THEN 0.0825 WHEN 'NL' THEN 0.21 WHEN 'SG' THEN 0.09 ELSE 0 END;
    END tax_rate;

    PROCEDURE recalculate (p_order_id IN orders.order_id%TYPE DEFAULT NULL) IS
    BEGIN
        -- Three passes because each SET sees the row as it was before the UPDATE.
        UPDATE orders o
        SET subtotal = (SELECT NVL(SUM(ol.line_total), 0) FROM order_lines ol WHERE ol.order_id = o.order_id)
        WHERE p_order_id IS NULL OR o.order_id = p_order_id;
        UPDATE orders
        SET discount = ROUND(subtotal * sales_pkg.promo_pct(promo_code, ordered_at) / 100, 2)
        WHERE p_order_id IS NULL OR order_id = p_order_id;
        UPDATE orders
        SET tax = ROUND((subtotal - discount) * sales_pkg.tax_rate(warehouse_id), 2)
        WHERE p_order_id IS NULL OR order_id = p_order_id;
    END recalculate;

    FUNCTION place_order (
        p_customer_id  IN customers.customer_id%TYPE,
        p_lines        IN order_line_tab,
        p_warehouse_id IN warehouses.warehouse_id%TYPE DEFAULT 1,
        p_promo_code   IN promotions.promo_code%TYPE DEFAULT NULL,
        p_sales_rep_id IN employees.employee_id%TYPE DEFAULT NULL
    ) RETURN orders.order_id%TYPE IS
        v_order_id orders.order_id%TYPE;
        v_short    VARCHAR2(4000);
        v_n        PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO v_n FROM customers WHERE customer_id = p_customer_id;
        IF v_n = 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'No such customer: ' || p_customer_id);
        END IF;
        IF p_lines IS NULL OR p_lines.COUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'An order needs at least one line.');
        END IF;
        SELECT COUNT(*) INTO v_n
        FROM TABLE(p_lines) l
        LEFT JOIN products p ON p.product_id = l.product_id
        WHERE p.product_id IS NULL OR p.discontinued = 1;
        IF v_n > 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'An order line names a missing or discontinued product.');
        END IF;
        IF p_promo_code IS NOT NULL AND promo_pct(p_promo_code, SYSDATE) = 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'Promotion ' || p_promo_code || ' is not valid today.');
        END IF;

        -- Lock the stock rows first, so two orders cannot both take the last unit.
        FOR r IN (SELECT s.product_id FROM stock s
                  WHERE s.warehouse_id = p_warehouse_id
                    AND s.product_id IN (SELECT l.product_id FROM TABLE(p_lines) l)
                  FOR UPDATE) LOOP
            NULL;
        END LOOP;

        SELECT LISTAGG(p.sku || ' (' || NVL(s.available, 0) || ' left, ' || l.qty || ' wanted)', ', ')
                   WITHIN GROUP (ORDER BY p.sku)
        INTO v_short
        FROM TABLE(p_lines) l
        JOIN products p ON p.product_id = l.product_id
        LEFT JOIN stock s ON s.product_id = l.product_id AND s.warehouse_id = p_warehouse_id
        WHERE NVL(s.available, 0) < l.qty;
        IF v_short IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20004, 'Not enough stock: ' || v_short);
        END IF;

        INSERT INTO orders (customer_id, sales_rep_id, ship_address_id, warehouse_id, promo_code)
        VALUES (p_customer_id, p_sales_rep_id,
                (SELECT MIN(address_id) KEEP (DENSE_RANK FIRST ORDER BY is_default DESC)
                 FROM addresses WHERE customer_id = p_customer_id AND kind = 'shipping'),
                p_warehouse_id, p_promo_code)
        RETURNING order_id INTO v_order_id;

        INSERT INTO order_lines (order_id, line_no, product_id, qty, unit_price)
        SELECT v_order_id, ROW_NUMBER() OVER (ORDER BY l.product_id), l.product_id, l.qty, p.list_price
        FROM TABLE(p_lines) l JOIN products p ON p.product_id = l.product_id;

        MERGE INTO stock s
        USING (SELECT product_id, SUM(qty) AS qty FROM TABLE(p_lines) GROUP BY product_id) l
        ON (s.product_id = l.product_id AND s.warehouse_id = p_warehouse_id)
        WHEN MATCHED THEN UPDATE SET s.reserved = s.reserved + l.qty, s.updated_at = SYSTIMESTAMP;

        recalculate(v_order_id);
        COMMIT;
        RETURN v_order_id;
    END place_order;

    FUNCTION quick_order (
        p_customer_id  IN NUMBER,
        p_product_id   IN NUMBER,
        p_qty          IN NUMBER DEFAULT 1,
        p_warehouse_id IN NUMBER DEFAULT 1
    ) RETURN orders.order_id%TYPE IS
    BEGIN
        RETURN place_order(p_customer_id, order_line_tab(order_line_t(p_product_id, p_qty)), p_warehouse_id);
    END quick_order;

    PROCEDURE advance_order (p_order_id IN orders.order_id%TYPE) IS
        v_status     orders.status%TYPE;
        v_warehouse  orders.warehouse_id%TYPE;
        v_total      NUMBER;
        v_invoice_id invoices.invoice_id%TYPE;
    BEGIN
        SELECT status, warehouse_id, total INTO v_status, v_warehouse, v_total
        FROM orders WHERE order_id = p_order_id FOR UPDATE;

        CASE v_status
            WHEN 'pending' THEN
                -- Payment is taken up front: invoice the order and settle it by card.
                INSERT INTO invoices (order_id, issued_on, due_on, amount, paid_amount)
                VALUES (p_order_id, TRUNC(SYSDATE), TRUNC(SYSDATE) + 30, v_total, v_total)
                RETURNING invoice_id INTO v_invoice_id;
                INSERT INTO payments (invoice_id, method, amount, paid_at, card_last4)
                VALUES (v_invoice_id, 'card', v_total, SYSTIMESTAMP, '4242');
                UPDATE orders SET status = 'paid' WHERE order_id = p_order_id;
            WHEN 'paid' THEN
                UPDATE orders SET status = 'picking' WHERE order_id = p_order_id;
            WHEN 'picking' THEN
                -- The movement trigger takes the units off on_hand; the reservation goes with them.
                INSERT INTO stock_movements (warehouse_id, product_id, qty, reason, order_id)
                SELECT v_warehouse, product_id, -SUM(qty), 'sale', p_order_id
                FROM order_lines WHERE order_id = p_order_id GROUP BY product_id;
                release_reservation(p_order_id, v_warehouse);
                UPDATE orders SET status = 'shipped', shipped_at = SYSTIMESTAMP WHERE order_id = p_order_id;
            WHEN 'shipped' THEN
                UPDATE orders SET status = 'delivered' WHERE order_id = p_order_id;
            ELSE
                RAISE_APPLICATION_ERROR(-20011, 'Order ' || p_order_id || ' is ' || v_status
                                                || '; nothing comes after that.');
        END CASE;
        COMMIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20010, 'No such order: ' || p_order_id);
    END advance_order;

    PROCEDURE cancel_order (p_order_id IN orders.order_id%TYPE, p_reason IN VARCHAR2) IS
        v_status    orders.status%TYPE;
        v_warehouse orders.warehouse_id%TYPE;
    BEGIN
        SELECT status, warehouse_id INTO v_status, v_warehouse
        FROM orders WHERE order_id = p_order_id FOR UPDATE;
        IF v_status NOT IN ('pending', 'paid', 'picking') THEN
            RAISE_APPLICATION_ERROR(-20011, 'Order ' || p_order_id || ' is ' || v_status
                                            || ' and cannot be cancelled.');
        END IF;
        release_reservation(p_order_id, v_warehouse);
        -- Money already taken goes back, which makes it a refund, not a cancellation.
        UPDATE orders SET status = CASE v_status WHEN 'pending' THEN 'cancelled' ELSE 'refunded' END
        WHERE order_id = p_order_id;
        INSERT INTO change_log (table_name, key_value, column_name, new_value)
        VALUES ('ORDERS', TO_CHAR(p_order_id), 'CANCEL_REASON', SUBSTR(p_reason, 1, 400));
        COMMIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20010, 'No such order: ' || p_order_id);
    END cancel_order;

    PROCEDURE customer_orders (
        p_customer_id IN  NUMBER,
        p_status      IN  VARCHAR2 DEFAULT NULL,
        p_orders      OUT SYS_REFCURSOR,
        p_by_status   OUT SYS_REFCURSOR
    ) IS
    BEGIN
        OPEN p_orders FOR
            SELECT order_id, order_no, ordered_at, status, line_count, units, total, sales_rep, warehouse
            FROM v_order_summary
            WHERE customer_id = p_customer_id AND (p_status IS NULL OR status = p_status)
            ORDER BY ordered_at DESC;
        OPEN p_by_status FOR
            SELECT status, COUNT(*) AS orders, SUM(total) AS total
            FROM orders WHERE customer_id = p_customer_id
            GROUP BY status ORDER BY orders DESC;
    END customer_orders;

    FUNCTION order_total (p_order_id IN NUMBER) RETURN NUMBER IS
        v_total NUMBER;
    BEGIN
        SELECT total INTO v_total FROM orders WHERE order_id = p_order_id;
        RETURN v_total;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN NULL;
    END order_total;

    FUNCTION order_total (p_order_id IN NUMBER, p_currency IN VARCHAR2) RETURN NUMBER IS
    BEGIN
        RETURN ROUND(order_total(p_order_id) / fx_rate(p_currency, SYSDATE), 2);
    END order_total;
END sales_pkg;
