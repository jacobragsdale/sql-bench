CREATE OR REPLACE TRIGGER trg_orders_status_audit
AFTER UPDATE OF status ON orders
FOR EACH ROW
WHEN (NEW.status <> OLD.status)
BEGIN
    INSERT INTO change_log (table_name, key_value, column_name, old_value, new_value)
    VALUES ('ORDERS', TO_CHAR(:NEW.order_id), 'STATUS', :OLD.status, :NEW.status);
END;
