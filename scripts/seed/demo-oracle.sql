-- Open orders hold stock; top up on_hand so every reservation is covered.
MERGE INTO stock s
USING (SELECT o.warehouse_id, ol.product_id, SUM(ol.qty) AS qty
       FROM orders o JOIN order_lines ol ON ol.order_id = o.order_id
       WHERE o.status IN ('pending', 'paid', 'picking')
       GROUP BY o.warehouse_id, ol.product_id) r
ON (s.warehouse_id = r.warehouse_id AND s.product_id = r.product_id)
WHEN MATCHED THEN UPDATE SET s.reserved = r.qty, s.on_hand = s.on_hand + r.qty;

