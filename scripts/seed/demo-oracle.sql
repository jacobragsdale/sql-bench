    g_raise_reason salary_history.reason%TYPE;

    PROCEDURE give_raise (p_employee_id IN NUMBER, p_pct IN NUMBER, p_reason IN VARCHAR2 DEFAULT 'merit');
    FUNCTION reports_to (p_manager_id IN NUMBER) RETURN org_tab PIPELINED;
    FUNCTION headcount (p_department_id IN NUMBER) RETURN NUMBER;
END hr_pkg;
